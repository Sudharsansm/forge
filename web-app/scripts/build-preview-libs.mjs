// Pre-bundles the libraries an app may import (React, React Router, ...) into one small script per library, plus the Tailwind browser
// build, as strings in src/preview/generated.ts. The window inlines only the ones an app uses, so nothing is ever downloaded.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const SHARED = ["react", "react/jsx-runtime", "react-dom", "react-dom/client"];
const LIBS = {
  "react": `import * as m from "react"; export default m;`,
  "react/jsx-runtime": `import * as m from "react/jsx-runtime"; export default m;`,
  "react-dom": `import * as m from "react-dom"; export default m;`,
  "react-dom/client": `import * as m from "react-dom/client"; export default m;`,
  // The preview has no real address, so BrowserRouter / createBrowserRouter are swapped for the hash versions (your code is unchanged).
  "react-router-dom": `import * as R from "react-router-dom"; export default { ...R, BrowserRouter: R.HashRouter, createBrowserRouter: R.createHashRouter };`,
  "lucide-react": `import * as m from "lucide-react"; export default m;`,
  "recharts": `import * as m from "recharts"; export default m;`,
  "clsx": `import * as m from "clsx"; export default { __esModule: true, ...m, default: m.default || m.clsx };`,
  "framer-motion": `import * as m from "framer-motion"; export default m;`,
};
const ALIASES = { "react-router": "react-router-dom" };

// react & react-dom are shared: every other library reads them from the registry instead of bundling its own copy.
const SELF = { name: "" };
const sharedPlugin = {
  name: "shared",
  setup(b) {
    b.onResolve({ filter: /^(react|react\/jsx-runtime|react-dom|react-dom\/client)$/ }, (a) =>
      a.importer.endsWith(`forge-entry:self-${SELF.name}.js`) ? undefined : { path: a.path, namespace: "shared" });
    b.onLoad({ filter: /.*/, namespace: "shared" }, (a) => ({ contents: `module.exports = window.__forgeLibs[${JSON.stringify(a.path)}];`, loader: "js" }));
  },
};

const out = {};
for (const [name, src] of Object.entries(LIBS)) {
  const isShared = SHARED.includes(name);
  SELF.name = name;
  const r = await build({
    stdin: { contents: src, resolveDir: process.cwd(), sourcefile: `forge-entry:${isShared ? "self" : "lib"}-${name}.js`, loader: "js" },
    bundle: true, minify: true, format: "iife", globalName: "__m", write: false, platform: "browser", target: "es2020", logLevel: "error",
    define: { "process.env.NODE_ENV": '"production"' },
    plugins: [sharedPlugin],
  });
  out[name] = `(function(){${r.outputFiles[0].text}\nwindow.__forgeLibs=window.__forgeLibs||{};window.__forgeLibs[${JSON.stringify(name)}]=__m.default;})();`;
}
const tailwind = readFileSync(new URL("../node_modules/@tailwindcss/browser/dist/index.global.js", import.meta.url), "utf8");
writeFileSync(new URL("../src/preview/generated.ts", import.meta.url),
  `// GENERATED by scripts/build-preview-libs.mjs - do not edit.\nexport const LIB_CHUNKS: Record<string, string> = ${JSON.stringify(out)};\n` +
  `export const LIB_ALIASES: Record<string, string> = ${JSON.stringify(ALIASES)};\nexport const TAILWIND_BROWSER = ${JSON.stringify(tailwind)};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k} ${Math.round(v.length / 1024)}KB`).join(", "), "tailwind", Math.round(tailwind.length / 1024) + "KB");
